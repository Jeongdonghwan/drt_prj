  const kw = p.kw;
  const b = p.breed;
  const kind = b?.kind || p.generic || 'dog';
  const cat = kind === 'cat';
  const kW = cat ? '고양이' : '강아지';
  const kN = cat ? '고양이' : '견종';
  const owner = cat ? '묘주' : '견주';
  const name = c.name;
  const pl = p.place;
  const where = pl ? pl.label : STORE.city;
  const store = BUSINESS.name.replace(`${BRAND} `, ''); // 부산본점·대구점
  const far = !!pl && pl.label !== STORE.city && (STORE.far.test(pl.label) || pl.scope === '시');
  const big = !!b && /대형/.test(b.size);
  const small = !!b && /소형/.test(b.size) && !/중형/.test(b.size);
  const longCoat = !!b && /장모|곱슬|양털|솜|웨이브|실크|풍성/.test(b.coat);
